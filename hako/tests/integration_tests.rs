#[test]
fn test_transpile_complex_control_flow() {
    let input = r#"
box test {
    run {
        for i in 0..10 {
            if i > 5 => {
                x = i
            } else {
                x = i
            }
            if x == 10 => {
                break
            }
        }
        loop {
            y = y + 1
            if y > 100 => {
                break
            }
        }
    }
}
"#;
    let (code, _, _) = transpile_string(input).unwrap();
    assert!(code.contains("for i in 0..10 {"));
    assert!(code.contains("if i > 5 {"));
    assert!(code.contains("} else {"));
    assert!(code.contains("break;"));
    assert!(code.contains("loop {"));
    assert!(code.contains("if y > 100 {"));
}

