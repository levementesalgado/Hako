use hako::transpile_file;
use hako::transpile_string;
use std::fs;
use std::path::Path;

// ===== Integration Tests =====

#[test]
fn test_transpile_string_returns_counts() {
    let input = r#"
box serial {
    COM1 = 0x3F8
}

flow default {
    serial
}
"#;
    let (code, boxes, flows) = transpile_string(input).unwrap();
    assert_eq!(boxes, 1);
    assert_eq!(flows, 1);
    assert!(!code.is_empty());
}

#[test]
fn test_transpile_string_produces_valid_rust() {
    let input = r#"
box serial {
    COM1 = 0x3F8
    config => default
    write_byte(b) => default
}

box vga {
    BASE = 0xB8000
    clear => default
    write(s) => default
}

flow default {
    serial
    vga
}
"#;
    let (code, _, _) = transpile_string(input).unwrap();

    // Check that the output contains valid Rust syntax
    assert!(code.contains("pub mod serial {"));
    assert!(code.contains("pub mod vga {"));
    assert!(code.contains("pub const COM1: u32 = 0x3F8;"));
    assert!(code.contains("pub const BASE: u32 = 0xB8000;"));
    assert!(code.contains("pub fn config()"));
    assert!(code.contains("pub fn write_byte(b: u32)"));
    assert!(code.contains("pub fn clear()"));
    assert!(code.contains("pub fn write(s: &str)"));
    assert!(code.contains("pub fn flow_default()"));
    assert!(code.contains("serial::run();"));
    assert!(code.contains("vga::run();"));
}

#[test]
fn test_transpile_file() {
    let input_path = Path::new("/tmp/test_input.hako");
    let output_path = Path::new("/tmp/test_output.rs");

    let input = r#"
box test {
    VALUE = 42
    run {
        x = VALUE
    }
}
"#;

    fs::write(input_path, input).unwrap();
    let result = transpile_file(input_path, output_path);
    assert!(result.is_ok());

    let (boxes, flows) = result.unwrap();
    assert_eq!(boxes, 1);
    assert_eq!(flows, 0);

    let output = fs::read_to_string(output_path).unwrap();
    assert!(output.contains("pub const VALUE: u32 = 42;"));
    assert!(output.contains("pub fn run()"));

    // Cleanup
    let _ = fs::remove_file(input_path);
    let _ = fs::remove_file(output_path);
}

