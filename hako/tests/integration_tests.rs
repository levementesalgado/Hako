#[test]
fn test_transpile_auto_mode_injects_constants() {
    let input = r#"
box serial {
    COM1 = 0x3F8
    config => default
    write_byte(b) => default
}
"#;
    let (code, _, _) = transpile_string(input).unwrap();
    // Auto mode should inject COM1 as extra argument
    assert!(code.contains("crate::hako_stdlib::serial_config(COM1)"));
    assert!(code.contains("crate::hako_stdlib::serial_write_byte(b, COM1)"));
}

#[test]
fn test_transpile_multiple_flows() {
    let input = r#"
box serial { COM1 = 0x3F8 }
box vga { BASE = 0xB8000 }

flow init {
    serial
    vga
}

flow run {
    vga
    serial
}
"#;
    let (code, _, flows) = transpile_string(input).unwrap();
    assert_eq!(flows, 2);
    assert!(code.contains("pub fn flow_init()"));
    assert!(code.contains("pub fn flow_run()"));
}

#[test]
