#[test]
fn test_transpile_real_world_example() {
    // A more realistic example of what Hako would be used for
    let input = r#"
box serial {
    COM1 = 0x3F8
    config => default
    write_byte(b) => default
    read_byte => default
}

box vga {
    BASE = 0xB8000
    clear => default
    write(s) => default
    put_char(c) => default
}

box keyboard {
    init => default
}

flow boot {
    serial
    vga
    keyboard
}

flow default {
    serial
    vga
}
"#;
    let (code, boxes, flows) = transpile_string(input).unwrap();
    assert_eq!(boxes, 3);
    assert_eq!(flows, 2);
    assert!(code.contains("pub mod serial {"));
    assert!(code.contains("pub mod vga {"));
    assert!(code.contains("pub mod keyboard {"));
    assert!(code.contains("pub fn flow_boot()"));
    assert!(code.contains("pub fn flow_default()"));
}
