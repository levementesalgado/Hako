#[test]
fn test_codegen_stdlib_mapping() {
    // Test all stdlib function mappings
    let input = r#"
box serial {
    COM1 = 0x3F8
    config => default
    write_byte(b) => default
    read_byte => default
}

box vga {
    put_char(c) => default
    write(s) => default
    clear => default
    scroll => default
    set_cursor(pos) => default
}

box io {
    outb(port, val) => default
    inb(port) => default
}

box kbd {
    init => default
}
"#;
    let output = transpile(input);
    assert!(output.contains("serial_config("));
    assert!(output.contains("serial_write_byte("));
    assert!(output.contains("serial_read_byte("));
    assert!(output.contains("vga_put_char("));
    assert!(output.contains("vga_write_str("));
    assert!(output.contains("vga_clear("));
    assert!(output.contains("vga_scroll("));
    assert!(output.contains("vga_set_cursor("));
    assert!(output.contains("port_outb("));
    assert!(output.contains("port_inb("));
    assert!(output.contains("keyboard_init("));
}

