use hako::codegen::Codegen;
use hako::parser::Parser;

// ===== Codegen Tests =====

fn transpile(input: &str) -> String {
    let mut p = Parser::new(input);
    let program = p.parse().unwrap();
    let mut cg = Codegen::new();
    cg.generate_full(&program)
}

#[test]
fn test_codegen_header() {
    let input = "box test { }";
    let output = transpile(input);
    assert!(output.contains("// Generated by Hako transpiler"));
}

#[test]
fn test_codegen_single_box() {
    let input = r#"
box serial {
    COM1 = 0x3F8
}
"#;
    let output = transpile(input);
    assert!(output.contains("pub mod serial {"));
    assert!(output.contains("pub const COM1: u32 = 0x3F8;"));
    assert!(output.contains("}"));
}

