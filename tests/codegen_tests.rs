#[test]
fn test_codegen_raw_function() {
    let input = r#"
box test {
    asm_test raw {
        out(al, x)
        "mov eax, 1"
        in(eax, result)
    }
}
"#;
    let output = transpile(input);
    assert!(output.contains("pub fn asm_test()"));
    assert!(output.contains("let mut __out_x: u8;"));
    assert!(output.contains("core::arch::asm!("));
    assert!(output.contains("\"mov eax, 1\""));
    assert!(output.contains("in(\"eax\") result"));
    assert!(output.contains("out(\"al\") __out_x"));
    assert!(output.contains("let x = __out_x;"));
}

